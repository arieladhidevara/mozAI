window.runPaintControlsChecks=async function(){
  const core=window.MosaicCore,{state,canvas,overlay,makeCanvas}=core,paint=window.MosaicPaint;
  const checks=[],assert=(ok,message)=>{if(!ok)throw Error(message)},pause=ms=>new Promise(resolve=>setTimeout(resolve,ms));
  const wait=async predicate=>{for(let i=0;i<200;i++){if(predicate())return;await pause(20)}throw Error('Paint controls timed out')};
  const sample=(image,x,y)=>Array.from(image.getContext('2d').getImageData(x,y,1,1).data);
  const pointer=(type,x,y)=>{const r=overlay.getBoundingClientRect();overlay.dispatchEvent(new PointerEvent(type,{bubbles:true,pointerType:'mouse',button:0,pointerId:70,clientX:r.left+x/canvas.width*r.width,clientY:r.top+y/canvas.height*r.height}))};
  const auth=window.MosaicAuth.request,account=window.MosaicAccount.request;let aiRequests=0;
  const block=async path=>{aiRequests++;throw Error('Unexpected AI request '+path)};
  window.MosaicAuth.request=async(path,...args)=>path.startsWith('/api/ai/')?block(path):auth(path,...args);
  window.MosaicAccount.request=async(path,...args)=>path.startsWith('/api/ai/')?block(path):account(path,...args);
  try{
    document.querySelector('.guide-skip')?.click();
    const base=makeCanvas(480,320),ctx=base.getContext('2d');ctx.fillStyle='#ddd';ctx.fillRect(0,0,480,320);
    const gradient=ctx.createLinearGradient(70,0,210,0);gradient.addColorStop(0,'#4d160a');gradient.addColorStop(.5,'#bd5022');gradient.addColorStop(1,'#eeb992');
    ctx.fillStyle=gradient;ctx.fillRect(70,60,140,180);ctx.fillStyle='#557799';ctx.fillRect(300,70,110,170);
    state.reference=base;core.setMaster(base,'Paint controls fixture',false);core.updateZoomFit();
    const mask=makeCanvas(480,320),m=mask.getContext('2d');m.fillRect(70,60,140,180);m.clearRect(120,110,20,25);
    let object=core.newGroup(mask,'Chair');object.name='Chair';object.mapPrepared=true;const objectId=object.id;
    const otherMask=makeCanvas(480,320);otherMask.getContext('2d').fillRect(300,70,110,170);
    const other=core.newGroup(otherMask,'Table');other.name='Table';other.mapPrepared=true;
    core.selectGroupMask(object);core.renderGroups();core.showQuickPrompt(null,true,false);window.MosaicMobile?.openAI();await pause(100);
    const add=()=>document.querySelector('[data-add-option="'+objectId+'"]');
    assert(add().textContent==='+'&&add().getAttribute('aria-label')==='Add option','Add option must be an accessible plus only');
    add().click();assert(document.querySelector('.add-option-menu'),'Chooser did not open');
    // The viewport stops bubbling in other tool paths. Capture must still dismiss it.
    const stop=event=>event.stopPropagation();overlay.addEventListener('pointerdown',stop);
    pointer('pointerdown',450,20);overlay.removeEventListener('pointerdown',stop);
    assert(!document.querySelector('.add-option-menu'),'Outside pointer with stopped propagation left chooser open');
    add().click();document.getElementById('quickAreaPromptInput').click();
    assert(!document.querySelector('.add-option-menu'),'Outside click did not close chooser');
    checks.push('Add option is plus only and its chooser closes on outside pointer/click');
    document.getElementById('quickPromptMore').click();
    const hue=document.getElementById('objectHue'),sat=document.getElementById('objectSaturation');
    assert(!hue.closest('.object-color-controls').hidden,'Selected object has no Hue/Saturation controls');
    const originalImage=core.composeApprovedCanvas().toDataURL(),history=state.undo.length;
    hue.dispatchEvent(new PointerEvent('pointerdown',{bubbles:true,pointerId:90}));
    for(const value of [35,75,120]){
      hue.value=value;hue.dispatchEvent(new Event('input',{bubbles:true}));
      await wait(()=>state.patches.get(object.active)?.colorAdjustment?.hue===value);
    }
    hue.dispatchEvent(new Event('change',{bubbles:true}));await pause(70);
    assert(state.undo.length===history+1,'A single slider drag made multiple Undo steps');
    assert(object.patchIds.length===1,'Hue on Original should create exactly one option');
    let view=core.composeApprovedCanvas(),front=sample(view,150,160),before=sample(base,150,160);
    assert(front[1]>front[0]&&front.join()!==before.join(),'Hue slider did not change the object hue');
    assert(sample(view,125,120).join()===sample(base,125,120).join(),'Hue affected an object mask hole');
    assert(sample(view,330,120).join()===sample(base,330,120).join(),'Hue changed another object');
    document.getElementById('undoBtn').click();object=state.groups.find(g=>g.id===objectId);
    assert(object.active===null&&core.composeApprovedCanvas().toDataURL()===originalImage,'Single Undo did not restore Original after the drag');
    document.getElementById('redoBtn').click();object=state.groups.find(g=>g.id===objectId);
    core.selectGroupMask(object);core.showQuickPrompt(null,true,false);window.MosaicMobile?.openAI();
    checks.push('Hue updates live, preserves holes/other objects, and the complete drag has one Undo step');
    const first=object.active,source=state.sources.get(state.patches.get(first).sourceId),sourceRGB=source.canvas.toDataURL();
    const second=await paint.duplicate(object);
    sat.value=0;sat.dispatchEvent(new Event('input',{bubbles:true}));sat.dispatchEvent(new Event('change',{bubbles:true}));
    await wait(()=>state.patches.get(second)?.colorAdjustment?.saturation===0);
    view=core.composeApprovedCanvas();front=sample(view,150,160);const shadow=sample(view,85,160),highlight=sample(view,195,160);
    assert(Math.max(...front.slice(0,3))-Math.min(...front.slice(0,3))<=1,'Saturation zero is not grayscale');
    assert(highlight[0]>shadow[0]+30,'Saturation flattened the shades');
    assert(source.canvas.toDataURL()===sourceRGB,'Sliders modified shared source RGB');
    await core.chooseGroupOption(object,first,{showPrompt:true});
    assert(hue.value==='120'&&sat.value==='100','Choosing prior option did not restore its slider settings');
    await core.chooseGroupOption(object,second,{showPrompt:true});
    assert(sat.value==='0','Choosing adjusted option lost its slider settings');
    checks.push('Saturation retains shades; each option has independent settings and immutable source pixels');
    const saved=await window.MosaicProjects.buildProjectData();
    const packed=saved.state.patches.$map.find(([id])=>id===second)[1];
    assert(packed.colorAdjustment.hue===120&&packed.colorAdjustment.saturation===0,'Project snapshot lost color settings');
    await paint.paint(object,'#b53939');
    const repainted=sample(core.composeApprovedCanvas(),150,160);
    assert(!state.patches.get(second).colorAdjustment&&repainted[0]>repainted[1]*2,'Paint used the old Hue/Saturation instead of the selected color');
    document.getElementById('undoBtn').click();object=state.groups.find(g=>g.id===objectId);
    assert(state.patches.get(second).colorAdjustment?.saturation===0,'Undo Paint lost the earlier adjustment');
    core.selectGroupMask(object);core.showQuickPrompt(null,true,false);window.MosaicMobile?.openAI();
    core.selectTool('paint');const picker=document.getElementById('paintColor');picker.value='#e02b33';picker.dispatchEvent(new Event('input'));
    const visibleBefore=core.composeApprovedCanvas().toDataURL(),undoBefore=state.undo.length;
    pointer('pointermove',150,160);await wait(()=>!document.getElementById('paintHoverOverlay').hidden);
    const hover=document.getElementById('paintHoverOverlay');
    assert(getComputedStyle(hover).opacity==='0.25'&&getComputedStyle(hover).pointerEvents==='none','Hover must be a 25% noninteractive overlay');
    const crop=core.groupMaskCrop(object);
    const tint=sample(hover,150-crop.x,160-crop.y),hole=sample(hover,125-crop.x,120-crop.y);
    assert(tint[0]===224&&tint[1]===43&&tint[2]===51&&hole[3]===0,'Hover tint or mask hole is incorrect');
    assert(core.composeApprovedCanvas().toDataURL()===visibleBefore&&state.undo.length===undoBefore,'Hover changed real pixels or history');
    pointer('pointermove',450,20);await wait(()=>hover.hidden);
    assert(getComputedStyle(hover).display==='none','Hidden preview is still drawn by canvas CSS');
    pointer('pointermove',150,160);overlay.closest('#viewport').dispatchEvent(new PointerEvent('pointerleave'));
    await pause(50);assert(hover.hidden,'Queued hover reappeared after pointer leave');
    pointer('pointermove',150,160);await wait(()=>!hover.hidden);core.selectTool('select');assert(hover.hidden,'Hover survived a tool change');
    checks.push('Paint hover uses the chosen color at 25%, respects holes, never changes pixels, and clears on leave/tool switch');
    const tool=document.getElementById('paintTool'),tooltip=getComputedStyle(tool,'::after'),swatch=getComputedStyle(tool,'::before');
    if(matchMedia('(min-width:851px)').matches)
      assert(tooltip.content.includes('Paint')&&tooltip.transform!=='none','Paint tooltip lost its centered label');
    assert(swatch.width==='14px'&&tooltip.width!=='14px','Paint swatch still overrides the tooltip box');
    assert(aiRequests===0,'Local controls made AI requests');
    checks.push('Paint tooltip and color swatch are separate; all controls use zero AI requests');
    core.selectGroupMask(object);core.showQuickPrompt(null,true,false);window.MosaicMobile?.openAI();
    if(document.getElementById('quickPromptMorePanel').hidden)document.getElementById('quickPromptMore').click();
    document.querySelector('.guide-skip')?.click();await pause(100);
    return {passed:checks.length,checks,aiRequests};
  }finally{window.MosaicAuth.request=auth;window.MosaicAccount.request=account}
};
