window.runPaintOptionChecks=async function(){
  const core=window.MosaicCore,{state,canvas,overlay,makeCanvas}=core,paint=window.MosaicPaint;
  const checks=[],assert=(ok,message)=>{if(!ok)throw Error(message)};
  document.title='Paint fixture starting';
  const record=checks.push.bind(checks);checks.push=message=>{document.title=message;return record(message)};
  const pause=ms=>new Promise(resolve=>setTimeout(resolve,ms));
  const wait=async predicate=>{for(let i=0;i<200;i++){if(predicate())return;await pause(20)}throw Error('Paint scenario timed out')};
  const sample=(image,x,y)=>Array.from(image.getContext('2d').getImageData(x,y,1,1).data);
  const originalAuth=window.MosaicAuth.request,originalAccount=window.MosaicAccount.request,confirm=window.confirm;
  const ensure=window.MosaicDiskCache.ensure;
  window.confirm=()=>true;
  let requests=0;const requestPaths=[];
  window.MosaicAuth.request=async(path,...args)=>{if(path.startsWith('/api/ai/')){requests++;requestPaths.push({path,step:document.title});throw Error('Paint must not call AI: '+path)}return originalAuth(path,...args)};
  window.MosaicAccount.request=async(path,...args)=>{if(path.startsWith('/api/ai/')){requests++;requestPaths.push({path,step:document.title});throw Error('Paint must not call AI: '+path)}return originalAccount(path,...args)};
  try{
    document.querySelector('.guide-skip')?.click();
    const base=makeCanvas(480,320),ctx=base.getContext('2d');ctx.fillStyle='#ccc';ctx.fillRect(0,0,480,320);
    const gradient=ctx.createLinearGradient(70,0,210,0);gradient.addColorStop(0,'#333');gradient.addColorStop(.5,'#888');gradient.addColorStop(1,'#ddd');
    ctx.fillStyle=gradient;ctx.fillRect(70,60,140,180);ctx.fillStyle='#998866';ctx.fillRect(300,70,110,170);
    state.reference=base;core.setMaster(base,'Paint fixture',false);core.updateZoomFit();
    const mask=makeCanvas(480,320),m=mask.getContext('2d');m.fillStyle='#fff';m.fillRect(70,60,140,180);m.clearRect(120,110,20,25);
    let object=core.newGroup(mask,'Chair');object.name='Chair';object.mapPrepared=true;const objectId=object.id;
    const otherMask=makeCanvas(480,320);otherMask.getContext('2d').fillRect(300,70,110,170);
    const other=core.newGroup(otherMask,'Table');other.name='Table';other.mapPrepared=true;
    core.selectGroupMask(object);core.showQuickPrompt(null,true,false);core.renderGroups();core.render();await pause(100);
    assert(document.querySelector('[data-add-option="'+object.id+'"]'),'Prompt Add option missing for original object');
    const add=document.querySelector('[data-add-option="'+object.id+'"]');add.click();
    assert(document.querySelector('.add-option-menu')?.textContent.includes('Duplicate option'),'Add chooser missing');
    document.querySelector('.add-option-menu button').click();
    await wait(()=>object.patchIds.length===1);
    const first=object.active,firstPatch=state.patches.get(first),firstSource=state.sources.get(firstPatch.sourceId);
    const originalLook=core.composeApprovedCanvas().toDataURL();
    assert(originalLook===base.toDataURL(),'Duplicate Original changed scene pixels');
    checks.push('Prompt Add option duplicates Original without changing the image');
    const sidebarAdd=document.querySelector('.region-group[data-group="'+object.id+'"] [data-region-action="add-option"]');sidebarAdd.click();
    assert(document.querySelector('.add-option-menu')?.textContent.includes('Generate option'),'Sidebar Add option has no Generate choice');
    document.querySelector('.add-option-menu button').click();await wait(()=>object.patchIds.length===2);
    const second=object.active,sourceBytes=firstSource.canvas.toDataURL();
    const secondSource=state.sources.get(state.patches.get(second).sourceId),secondCanvas=secondSource.canvas;
    // Generate opens the existing composer and waits for an explicit submission.
    document.querySelector('.region-group[data-group="'+object.id+'"] [data-region-action="add-option"]').click();
    document.querySelectorAll('.add-option-menu button')[1].click();
    assert(state.draftGroupId===object.id&&!document.getElementById('quickAreaPromptForm').classList.contains('hidden'),'Generate did not open this object composer');
    const picker=document.getElementById('paintColor');picker.value='#c52b2b';picker.dispatchEvent(new Event('change'));
    assert(state.tool==='paint','Color choice did not activate Paint');
    const firstCanvas=firstSource.canvas;firstSource.canvas=null;let releaseLoad;
    window.MosaicDiskCache.ensure=(target,field)=>target===firstSource?new Promise(resolve=>{releaseLoad=()=>{target.canvas=firstCanvas;resolve()}}):ensure(target,field);
    const pendingChoice=core.chooseGroupOption(object,first);
    const r=overlay.getBoundingClientRect();overlay.dispatchEvent(new PointerEvent('pointerdown',{bubbles:true,pointerType:'mouse',button:0,pointerId:70,
      clientX:r.left+150/480*r.width,clientY:r.top+160/320*r.height}));
    await wait(()=>state.patches.get(second)?.paintColor==='#c52b2b');
    releaseLoad();assert(await pendingChoice===false&&object.active===second,'A delayed option load overrode the newer Paint choice');
    window.MosaicDiskCache.ensure=ensure;
    const view=core.composeApprovedCanvas(),dark=sample(view,85,160),light=sample(view,195,160);
    assert(dark[0]>dark[1]&&light[0]>light[1]&&light[0]>dark[0]+20,'Paint flattened shades or failed to tint red');
    assert(JSON.stringify(sample(view,125,120))===JSON.stringify(sample(base,125,120)),'Paint leaked into mask hole');
    assert(JSON.stringify(sample(view,330,120))===JSON.stringify(sample(base,330,120)),'Paint changed another object');
    assert(object.active===second&&object.patchIds.length===2,'Paint changed or added an extra option');
    assert(firstSource.canvas.toDataURL()===sourceBytes,'Painting a duplicate mutated the old RGB');
    checks.push('Bucket click paints only the active copy, retaining shades, holes and other objects');
    // Disk eviction changes the old live source object; Undo retains an immutable RGB reference.
    secondSource.canvas=null;
    document.getElementById('undoBtn').click();object=state.groups.find(g=>g.id===objectId);
    assert(core.composeApprovedCanvas().toDataURL()===originalLook,'Undo did not restore RGB');
    secondSource.canvas=secondCanvas;
    document.getElementById('redoBtn').click();object=state.groups.find(g=>g.id===objectId);
    assert(state.patches.get(object.active).paintColor==='#c52b2b','Redo lost paint');
    await core.chooseGroupOption(object,first);
    assert(core.composeApprovedCanvas().toDataURL()===originalLook,'Prior option changed after painting copy');
    await core.chooseGroupOption(object,null);
    const auto=await paint.paint(object,'#386fc1');assert(auto&&object.active===auto&&object.patchIds.length===3,'Paint on Original did not create a new option');
    checks.push('Undo/Redo and option switching preserve independent images; Original paint creates its own option');
    // A moved RGBA Create layer: Paint must retain geometry and partially transparent edges.
    const cutout=makeCanvas(60,70),c=cutout.getContext('2d');c.fillStyle='rgba(130,140,150,.4)';c.fillRect(0,0,60,70);c.fillStyle='#aaa';c.fillRect(10,10,40,50);
    const cm=makeCanvas(60,70);cm.getContext('2d').fillRect(0,0,60,70);
    const full=makeCanvas(480,320);full.getContext('2d').drawImage(cm,240,210);
    const created=core.newGroup(full,'Created');created.name='Created';created.createdLocally=true;
    const sid=core.uid('source'),pid=core.uid('patch');state.sources.set(sid,{id:sid,canvas:cutout,crop:{x:240,y:210,width:60,height:70}});
    const corners=[{x:250,y:205},{x:310,y:215},{x:305,y:285},{x:245,y:275}];
    state.patches.set(pid,{id:pid,groupId:created.id,sourceId:sid,mask:cm,maskOffset:{x:240,y:210},bbox:{x:240,y:210,w:60,h:70},corners,name:'RGBA',createObject:true});
    created.patchIds=[pid];created.active=pid;core.refreshGroupFootprint(created);
    const copyId=await paint.duplicate(created);assert(copyId,'Create duplicate failed');
    const alphaBefore=Array.from(state.sources.get(state.patches.get(copyId).sourceId).canvas.getContext('2d').getImageData(0,0,60,70).data).filter((v,i)=>i%4===3);
    const layerBefore=core.renderedPatchLayer(state.patches.get(copyId)).getContext('2d').getImageData(0,0,480,320).data;
    await paint.adjust(created,75,140);
    const layerAfter=core.renderedPatchLayer(state.patches.get(copyId)).getContext('2d').getImageData(0,0,480,320).data;
    assert(layerBefore.every((value,index)=>index%4!==3||value===layerAfter[index]),'Hue/Saturation changed transformed PNG alpha');
    await paint.paint(created,'#45a555');const painted=state.patches.get(copyId),rgb=state.sources.get(painted.sourceId).canvas.getContext('2d').getImageData(0,0,60,70).data;
    assert(alphaBefore.every((a,i)=>a===rgb[i*4+3]),'Paint changed PNG alpha');
    assert(JSON.stringify(painted.corners)===JSON.stringify(corners),'Paint changed moved/skewed placement');
    checks.push('Created RGBA copies preserve every alpha value and their moved/skewed placement');
    assert(requests===0,'Local painting or duplication made AI requests: '+JSON.stringify(requestPaths));
    const paintAIRequests=requests,saved=await window.MosaicProjects.buildProjectData();
    await window.MosaicProjects.loadProjectFile(new File([JSON.stringify(saved)],'paint.moz',{type:'application/json'}));
    assert(state.patches.get(copyId)?.paintColor==='#45a555','Saved project lost paint');
    assert(state.groups.find(g=>g.id===objectId)?.patchIds.length===3,'Saved project lost copied options');
    assert(requestPaths.every(item=>item.path==='/api/ai/object-map'),'Project load triggered unexpected AI work');
    checks.push('Painted options persist in .moz; duplicate and paint make zero AI requests');
    core.selectGroupMask(state.groups.find(g=>g.id===objectId));core.showQuickPrompt(null,true,false);window.MosaicMobile?.openAI();
    document.querySelector('.guide-skip')?.click();
    await pause(100);return {passed:checks.length,checks,paintAIRequests,projectLoadMapRequests:requests-paintAIRequests};
  }finally{window.MosaicAuth.request=originalAuth;window.MosaicAccount.request=originalAccount;window.confirm=confirm;window.MosaicDiskCache.ensure=ensure}
};

window.runPaintShapeChecks=async function(){
  const core=window.MosaicCore,{state,makeCanvas}=core,assert=(ok,msg)=>{if(!ok)throw Error(msg)};
  const mask=(x,y,w,h)=>{const c=makeCanvas(480,320);c.getContext('2d').fillRect(x,y,w,h);return c};
  const base=makeCanvas(480,320),ctx=base.getContext('2d');ctx.fillStyle='#ccc';ctx.fillRect(0,0,480,320);
  ctx.fillStyle='#669966';ctx.fillRect(80,70,180,180);state.reference=base;core.setMaster(base,'Paint shape',false);
  const object=core.newGroup(mask(80,70,180,180),'Chair');object.name='Reshaped chair';
  const source=makeCanvas(480,320);source.getContext('2d').drawImage(base,0,0);const sc=source.getContext('2d');
  sc.fillStyle='#ccc';sc.fillRect(160,70,100,180);
  const patch={id:'shape-paint',groupId:object.id,sourceId:'shape-paint-source',mask:mask(80,70,180,180),bbox:{x:80,y:70,w:180,h:180},
    geometryObjectMask:mask(80,70,80,180),editMode:'shape',name:'Smaller chair'};
  state.patches.set(patch.id,patch);state.sources.set(patch.sourceId,{id:patch.sourceId,canvas:source});object.active=patch.id;object.patchIds=[patch.id];
  const revealed=makeCanvas(480,320),rc=revealed.getContext('2d');rc.fillStyle='#ccc';rc.fillRect(160,70,100,180);
  state.objectReconstruction={events:[{id:'paint-shape-event',ownershipVersion:2,operation:'shape',groupId:object.id,patchId:patch.id,sourceId:patch.sourceId,revealedRGB:revealed,assignments:[]}]};
  window.MosaicReconstruction.sync();const before=core.composeApprovedCanvas().toDataURL();
  const copy=await window.MosaicPaint.duplicate(object);assert(copy&&object.active===copy,'Shape copy failed');
  assert(core.composeApprovedCanvas().toDataURL()===before,'Shape duplicate restored the old silhouette or changed revealed background');
  await window.MosaicPaint.paint(object,'#cc3333');
  const view=core.composeApprovedCanvas().getContext('2d'),front=view.getImageData(110,150,1,1).data,back=view.getImageData(220,150,1,1).data;
  assert(front[0]>front[1]*2,'Paint did not recolor new silhouette');
  assert(back[0]===204&&back[1]===204&&back[2]===204,'Paint affected revealed background');
  await core.chooseGroupOption(object,patch.id);assert(core.composeApprovedCanvas().toDataURL()===before,'Original Shape option changed');
  return {passed:2,checks:['Shape duplicate retains its revealed background','Paint colors only the new silhouette and preserves the previous Shape option']};
};
